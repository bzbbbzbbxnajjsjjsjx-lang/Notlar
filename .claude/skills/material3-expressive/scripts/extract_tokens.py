#!/usr/bin/env python3
"""Render androidx material3 token objects as Markdown tables.

Usage: extract_tokens.py <material3 module dir> <output file> <version label>
"""
import re
import sys
from pathlib import Path

PROP = re.compile(r"^\s*(?:inline\s+)?(?:const\s+)?val\s+(\w+)\s*(?::\s*[\w.<>, ]+)?\s*(?:=\s*(.+)|\n\s*get\(\)\s*=\s*(.+))", re.M)
SHORTEN = [
    (r"androidx\.compose\.ui\.unit\.", ""), (r"androidx\.compose\.ui\.text\.font\.", ""),
    (r"ColorSchemeKeyTokens\.", "color."), (r"ShapeKeyTokens\.", "shape."),
    (r"TypographyKeyTokens\.", "type."), (r"ElevationTokens\.", "elevation."),
    (r"MotionSchemeKeyTokens\.", "motion."), (r"PaletteTokens\.", "palette."),
    (r"\.0\.dp\b", ".dp"), (r"\.0f\b", ""),
]


def clean(v):
    v = v.strip().rstrip(",")
    for a, b in SHORTEN:
        v = re.sub(a, b, v)
    return v.replace("|", "\\|")


def main():
    module, out, version = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    tokens = module / "src/commonMain/kotlin/androidx/compose/material3/tokens"
    parts = [f"# material3 {version} design tokens", "",
             "Generated by `scripts/extract_tokens.py` from `androidx.compose.material3.tokens`.",
             "These objects are internal to the library; use them to look up the exact spec values",
             "(sizes, shapes, colors roles, type roles, motion) that the public `*Defaults` expose.",
             "`color.X` = `MaterialTheme.colorScheme.x`, `shape.X` = `MaterialTheme.shapes.x`,",
             "`type.X` = `MaterialTheme.typography.x`.", ""]
    for path in sorted(tokens.glob("*.kt")):
        src = path.read_text(encoding="utf-8")
        rows = []
        for m in PROP.finditer(src):
            value = m.group(2) or m.group(3) or ""
            if value.strip().endswith(("(", "=")) or not value.strip():
                # Multi-line value: take the following lines up to the closing paren.
                start = m.end()
                tail = src[start:start + 400].split("\n")
                extra = []
                for line in tail[1:]:
                    extra.append(line.strip())
                    if line.strip().startswith(")") or line.strip().endswith(")"):
                        break
                value = value + " " + " ".join(extra)
            rows.append((m.group(1), clean(value)))
        if not rows:
            continue
        parts.append(f"## {path.stem}")
        parts.append("")
        parts.append("| Token | Value |")
        parts.append("| --- | --- |")
        parts.extend(f"| {n} | `{v}` |" for n, v in rows)
        parts.append("")
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
